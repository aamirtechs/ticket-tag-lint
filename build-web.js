'use strict';

// Mini-bundler: wraps every src/ module in a CommonJS-style define() and emits
// docs/app.js with a tiny require shim, so the browser app runs the exact same
// code as the library and CLI. No dependencies, no build tooling beyond Node.
// Excludes src/cli.js, which is Node-only (fs, process and file output).

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'src');
const OUT = path.join(__dirname, 'docs', 'app.js');
const EXCLUDE = new Set(['cli.js']);

function collect(dir, baseDir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...collect(full, baseDir));
    else if (entry.name.endsWith('.js') && !EXCLUDE.has(entry.name)) {
      const key = path.relative(baseDir, full).replace(/\\/g, '/').replace(/\.js$/, '');
      out.push({ key, code: fs.readFileSync(full, 'utf8') });
    }
  }
  return out;
}

const modules = collect(SRC, SRC).map(({ key, code }) => ({ key: 'src/' + key, code }));

const header = `/* ticket-tag-lint browser bundle. Generated by build-web.js from src/. Do not edit by hand. */\n'use strict';\n`;
const shim = `
const __modules = {};
const __cache = {};
function __define(key, fn) { __modules[key] = fn; }
function __resolve(fromKey, request) {
  const parts = fromKey.split('/').slice(0, -1);
  for (const seg of request.split('/')) {
    if (seg === '.' || seg === '') continue;
    else if (seg === '..') parts.pop();
    else parts.push(seg);
  }
  return parts.join('/');
}
function __load(key) {
  if (__cache[key]) return __cache[key].exports;
  const module = { exports: {} };
  __cache[key] = module;
  const localRequire = (request) => __load(__resolve(key, request));
  __modules[key](module, module.exports, localRequire);
  return module.exports;
}
`;
const body = modules.map(({ key, code }) =>
  `__define(${JSON.stringify(key)}, function(module, exports, require) {\n${code}\n});`
).join('\n');
const footer = `\nwindow.TicketTagLint = __load('src/index');\n`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + shim + body + footer, 'utf8');
console.log(`Wrote ${path.relative(process.cwd(), OUT)} with ${modules.length} modules.`);
